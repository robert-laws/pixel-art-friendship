ADV = 6
H = 7


def text_width(s, scale=1):
    return max(0, (len(s.replace("*", "")) * ADV - 1) * scale)


def draw_text(frame, x, y, s, color=(255, 255, 255), scale=1, shadow=None, hi=(255, 224, 96), limit=None):
    """Draw uppercase text into an (H,W,3) uint8 frame. '*' toggles the highlight colour.
    `limit` = number of visible characters (typewriter effect)."""
    Hh, Ww = frame.shape[:2]
    cx = x
    shown = 0
    cur = color
    for ch in s:
        if ch == "*":
            cur = hi if cur == color else color
            continue
        if limit is not None and shown >= limit:
            break
        shown += 1
        g = _G.get(ch.upper(), _G["?"])
        if g.any():
            ys, xs = np.nonzero(g)
            for (ox, oy, col) in ([(1 * scale, 1 * scale, shadow)] if shadow else []) + [(0, 0, cur)]:
                for gy, gx in zip(ys, xs):
                    px0, py0 = cx + gx * scale + ox, y + gy * scale + oy
                    x1, y1 = min(px0 + scale, Ww), min(py0 + scale, Hh)
                    if px0 < 0 or py0 < 0 or x1 <= px0 or y1 <= py0:
                        continue
                    frame[py0:y1, px0:x1] = col
        cx += ADV * scale
    return cx
