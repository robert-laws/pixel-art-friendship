"""A tiny 5x7 bitmap font (uppercase only, like an 8-bit console)."""
import numpy as np

_G = {}


def _add(ch, *rows):
    assert len(rows) == 7, ch
    _G[ch] = np.array([[1 if c == "#" else 0 for c in r.ljust(5, ".")[:5]] for r in rows], dtype=np.uint8)


